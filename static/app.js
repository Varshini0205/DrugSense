function switchSection(section) {

    if (!sections.includes(section)) {
        return;
    }


    document
        .querySelectorAll(".nav-item")
        .forEach((button) => {

            button.classList.toggle(
                "active",
                button.dataset.section === section
            );

        });


    document
        .querySelectorAll(".page-section")
        .forEach((element) => {

            element.classList.remove(
                "active-section"
            );

        });


    const target =
        byId(`section-${section}`);

    if (target) {
        target.classList.add(
            "active-section"
        );
    }


    const meta =
        sectionMeta[section];

    if (meta) {

        setText(
            "pageTitle",
            meta.title
        );

        setText(
            "pageDescription",
            meta.description
        );

    }


    if (
        section === "dataset" ||
        section === "model"
    ) {
        loadStats();
    }

}


