/* =========================================================
   MODEL COMPARISON
========================================================= */

function renderModelComparison(
    models
) {

    const container =
        byId("modelComparison");


    if (!container) {
        return;
    }


    container.innerHTML = "";


    if (
        !Array.isArray(models) ||
        models.length === 0
    ) {

        container.innerHTML =
            '<span class="empty-tag">No comparison data available.</span>';

        return;
    }


    models.forEach(
        (model) => {

            const accuracy =
                Number(
                    model.accuracy
                ) || 0;


            const width =
                Math.max(
                    0,
                    Math.min(
                        100,
                        accuracy * 100
                    )
                );


            const row =
                document.createElement(
                    "div"
                );


            row.className =
                "comparison-row";


            row.innerHTML = `
                <div class="comparison-name">
                    ${escapeHTML(
                        model.name ||
                        "Model"
                    )}
                </div>

                <div class="comparison-track">
                    <div
                        class="comparison-fill"
                        style="width:${width}%"
                    ></div>
                </div>

                <div class="comparison-value">
                    ${(
                        accuracy * 100
                    ).toFixed(2)}%
                </div>
            `;


            container.appendChild(
                row
            );

        }
    );

}


/* =========================================================
   UTILITIES
========================================================= */

function uniqueDisplayValues(
    values
) {

    if (!Array.isArray(values)) {
        return [];
    }

    const seen = new Set();

    return values.filter(
        (value) => {

            const text =
                String(value ?? "").trim();

            const key =
                text.toLowerCase();

            if (!text || seen.has(key)) {
                return false;
            }

            seen.add(key);

            return true;
        }
    );
}

function capitalizeWords(
    value
) {

    if (
        value === null ||
        value === undefined
    ) {
        return "";
    }


    return String(value)
        .trim()
        .replace(/\b\w/g, (character) =>
            character.toUpperCase()
        );

}


function capitalize(
    value
) {

    const text =
        String(value);


    if (!text) {
        return "";
    }


    return (
        text.charAt(0).toUpperCase() +
        text.slice(1)
    );

}


