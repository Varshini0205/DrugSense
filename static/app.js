async function analyzeReview() {

    const review =
        reviewInput.value.trim();


    hideElement("errorState");


    if (!review) {

        showError(
            "Review required",
            "Please enter a patient review before analysis."
        );

        return;
    }


    if (review.length > 10000) {

        showError(
            "Review too long",
            "Please keep the review under 10,000 characters."
        );

        return;
    }


    analyzeButton.disabled = true;

    showElement("loadingState");


    try {

        const response =
            await fetch(
                "/analyze",
                {
                    method: "POST",

                    headers: {
                        "Content-Type":
                            "application/json"
                    },

                    body: JSON.stringify({
                        review: review
                    })
                }
            );


        const result =
            await response.json();


        if (!response.ok) {

            throw new Error(
                result.error ||
                "Analysis failed."
            );

        }


        renderResults(result);

        hideElement("loadingState");


        switchSection("nlp");


    } catch (error) {

        hideElement("loadingState");

        showError(
            "Analysis failed",
            error.message ||
            "Unable to analyze the review."
        );

    } finally {

        analyzeButton.disabled = false;

    }

}


