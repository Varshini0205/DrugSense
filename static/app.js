/* =========================================================
   QUICK WORKSPACE RESULT
========================================================= */

function renderQuickResults(
    result,
    nlp
) {

    const entities =
        nlp.entities || {};


    const drugs =
        uniqueDisplayValues(
            getArray(
                entities,
                "drugs"
            )
        );


    const conditions =
        uniqueDisplayValues(
            getArray(
                entities,
                "conditions"
            )
        );


    const symptoms =
        uniqueDisplayValues(
            getArray(
                entities,
                "symptoms"
            )
        );


    const prediction =
        result.prediction || {};


    setText(
        "workspaceDrugs",
        drugs.length
            ? drugs
                .map(
                    (item) =>
                        capitalizeWords(
                            String(item)
                        )
                )
                .join(", ")
            : "None detected"
    );


    setText(
        "workspaceConditions",
        conditions.length
            ? conditions
                .map(
                    (item) =>
                        capitalizeWords(
                            String(item)
                        )
                )
                .join(", ")
            : "None detected"
    );


    setText(
        "workspaceSymptoms",
        symptoms.length
            ? symptoms
                .map(
                    (item) =>
                        capitalizeWords(
                            String(item)
                        )
                )
                .join(", ")
            : "None detected"
    );


    setText(
        "workspacePrediction",
        prediction.condition ||
        "Not available"
    );


    showElement(
        "workspaceResult"
    );

}


/* =========================================================
   NLP RENDERING
========================================================= */

function renderNLP(
    result,
    nlp
) {

    const entities =
        nlp.entities || {};


    renderTags(
        "nlpDrugs",
        getArray(
            entities,
            "drugs"
        )
    );


    renderTags(
        "nlpConditions",
        getArray(
            entities,
            "conditions"
        )
    );


    renderTags(
        "nlpSymptoms",
        getArray(
            entities,
            "symptoms"
        )
    );


    const sideEffects =
        getArray(
            entities,
            "side_effects"
        );


    renderTags(
        "nlpSideEffects",
        sideEffects.map(
            (item) => {

                if (
                    item &&
                    typeof item === "object"
                ) {
                    return item.symptom ||
                        item.text ||
                        "Side effect";
                }

                return item;

            }
        )
    );


    const sentiment =
        nlp.sentiment || {};


    setText(
        "nlpSentiment",
        sentiment.label
            ? capitalize(
                sentiment.label
            )
            : "Neutral"
    );


    setText(
        "nlpSentimentScore",
        `Score: ${
            sentiment.score ?? 0
        }`
    );


    const treatment =
        getArray(
            nlp,
            "treatment_response"
        );


    if (treatment.length) {

        const responses =
            treatment
                .map(
                    (item) =>
                        item.response ||
                        item.text
                )
                .filter(Boolean);


        setText(
            "nlpTreatment",
            responses.length
                ? responses.map(capitalizeWords).join(", ")
                : "Detected"
        );

    } else {

        setText(
            "nlpTreatment",
            "No clear response"
        );

    }


    const severity =
        getArray(
            nlp,
            "severity"
        );


    if (severity.length) {

        const severityValues =
            severity
                .map(
                    (item) =>
                        item.severity ||
                        item.text
                )
                .filter(Boolean);


        setText(
            "nlpSeverity",
            severityValues.join(", ")
        );

    } else {

        setText(
            "nlpSeverity",
            "Not detected"
        );

    }


    const uncertainty =
        getArray(
            nlp,
            "uncertainty"
        );


    if (uncertainty.length) {

        setText(
            "nlpUncertainty",
            uncertainty
                .map(
                    (item) =>
                        item.text ||
                        item.expression ||
                        String(item)
                )
                .join(", ")
        );

    } else {

        setText(
            "nlpUncertainty",
            "Not detected"
        );

    }


    setText(
        "signalNegation",
        getArray(
            nlp,
            "negation"
        ).length
    );


    setText(
        "signalTemporal",
        getArray(
            nlp,
            "temporal_information"
        ).length
    );


    setText(
        "signalCausality",
        getArray(
            nlp,
            "causal_relations"
        ).length
    );


    setText(
        "signalRelations",
        getRelations(result, nlp).length
    );


    const medicationDetails =
        nlp.medication_details ||
        {};


    renderSimpleList(
        "nlpDosages",
        getArray(
            medicationDetails,
            "dosages"
        )
    );


    renderSimpleList(
        "nlpFrequencies",
        getArray(
            medicationDetails,
            "frequencies"
        )
    );


    renderSimpleList(
        "nlpDurations",
        getArray(
            medicationDetails,
            "durations"
        )
    );


    renderRelations(
        getRelations(result, nlp)
    );


    renderTimeline(
        getArray(
            nlp,
            "timeline"
        )
    );

}


/* =========================================================
   TAGS
========================================================= */

function renderTags(
    elementId,
    values
) {

    const container =
        byId(elementId);


    if (!container) {
        return;
    }


    container.innerHTML = "";


    const uniqueValues =
        uniqueDisplayValues(values);


    if (
        uniqueValues.length === 0
    ) {

        container.innerHTML =
            '<span class="empty-tag">None detected</span>';

        return;
    }


    uniqueValues.forEach(
        (value) => {

            const tag =
                document.createElement(
                    "span"
                );


            tag.className =
                "tag";


            tag.textContent =
                capitalizeWords(
                    String(value)
                );


            container.appendChild(
                tag
            );

        }
    );

}


/* =========================================================
   SIMPLE LIST
========================================================= */

function renderSimpleList(
    elementId,
    values
) {

    const container =
        byId(elementId);


    if (!container) {
        return;
    }


    if (
        !Array.isArray(values) ||
        values.length === 0
    ) {

        container.textContent =
            "None detected";

        return;
    }


    container.innerHTML =
        values
            .map(
                (item) => {

                    if (
                        item &&
                        typeof item === "object"
                    ) {

                        return Object
                            .values(item)
                            .join(" ");

                    }

                    return String(item);

                }
            )
            .map(
                (value) =>
                    `<span class="tag">${escapeHTML(value)}</span>`
            )
            .join(" ");

}


/* =========================================================
   RELATIONS
========================================================= */

function renderRelations(
    relations
) {

    const container =
        byId("nlpRelations");


    if (!container) {
        return;
    }


    container.innerHTML = "";


    if (
        !Array.isArray(relations) ||
        relations.length === 0
    ) {

        container.innerHTML =
            '<span class="empty-tag">No relations detected</span>';

        return;
    }


    relations.forEach(
        (relation) => {

            const item =
                document.createElement(
                    "div"
                );


            item.className =
                "relation-item";


            const subject =
                relation.subject ||
                "Unknown";


            const relationName =
                relation.relation ||
                "related to";


            const object =
                relation.object ||
                "Unknown";


            item.innerHTML = `
                <span>
                    ${escapeHTML(subject)}
                </span>

                &nbsp;?&nbsp;

                <span>
                    ${escapeHTML(relationName)}
                </span>

                &nbsp;?&nbsp;

                <span>
                    ${escapeHTML(object)}
                </span>
            `;


            container.appendChild(
                item
            );

        }
    );

}


