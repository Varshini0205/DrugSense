let statsLoaded = false;


async function loadStats() {

    if (statsLoaded) {
        return;
    }


    try {

        const response =
            await fetch(
                "/api/stats"
            );


        if (!response.ok) {
            throw new Error(
                "Unable to load statistics."
            );
        }


        const data =
            await response.json();


        renderDatasetAnalytics(
            data
        );


        renderModelAnalytics(
            data
        );


        statsLoaded = true;


    } catch (error) {

        console.error(
            "Statistics error:",
            error
        );

    }

}


/* =========================================================
   DATASET ANALYTICS
========================================================= */

function renderDatasetAnalytics(
    data
) {

    const dataset =
        data.dataset || {};


    setText(
        "datasetTraining",
        formatNumber(
            dataset.training_reviews
        )
    );


    setText(
        "datasetTest",
        formatNumber(
            dataset.test_reviews
        )
    );


    setText(
        "datasetConditions",
        formatNumber(
            dataset.training_conditions
        )
    );


    setText(
        "datasetFeatures",
        formatNumber(
            dataset.tfidf_features
        )
    );


    const container =
        byId("datasetBars");


    if (!container) {
        return;
    }


    const values = [
        {
            name: "Training Reviews",
            value:
                Number(
                    dataset.training_reviews
                ) || 0
        },

        {
            name: "Test Reviews",
            value:
                Number(
                    dataset.test_reviews
                ) || 0
        },

        {
            name: "Training Conditions",
            value:
                Number(
                    dataset.training_conditions
                ) || 0
        },

        {
            name: "TF-IDF Features",
            value:
                Number(
                    dataset.tfidf_features
                ) || 0
        }
    ];


    const max =
        Math.max(
            ...values.map(
                (item) =>
                    item.value
            ),
            1
        );


    container.innerHTML =
        values
            .map(
                (item) => {

                    const width =
                        (
                            item.value /
                            max
                        ) * 100;


                    return `
                        <div class="distribution-row">

                            <div class="distribution-name">
                                ${escapeHTML(item.name)}
                            </div>

                            <div class="distribution-track">
                                <div
                                    class="distribution-fill"
                                    style="width:${width}%"
                                ></div>
                            </div>

                            <div class="distribution-value">
                                ${formatNumber(item.value)}
                            </div>

                        </div>
                    `;

                }
            )
            .join("");

}


