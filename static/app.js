/* =========================================================
   PREDICTION
========================================================= */

function renderPrediction(
    result
) {

    const prediction =
        result.prediction || {};


    const condition =
        prediction.condition ||
        result.predicted_condition ||
        "Not available";


    const model =
        prediction.model ||
        "Linear Support Vector Machine";


    const score =
        prediction.normalized_score ??
        prediction.score;


    setText(
        "predictedCondition",
        condition
            ? capitalizeWords(condition)
            : "Not available"
    );


    setText(
        "predictionModel",
        model
    );


    if (
        prediction.normalized_score !==
        undefined &&
        prediction.normalized_score !==
        null
    ) {

        setText(
            "predictionScore",
            `${(
                Number(
                    prediction.normalized_score
                ) * 100
            ).toFixed(2)}%`
        );

    } else {

        setText(
            "predictionScore",
            score !== undefined &&
            score !== null
                ? Number(score).toFixed(4)
                : "ï¿½"
        );

    }


    renderPredictionBars(
        prediction
    );


    hideElement(
        "predictionEmpty"
    );


    showElement(
        "predictionResults"
    );

}


/* =========================================================
   PREDICTION BARS
========================================================= */

function renderPredictionBars(
    prediction
) {

    const container =
        byId("predictionBars");


    if (!container) {
        return;
    }


    container.innerHTML = "";


    let predictions =
        prediction.top_predictions ||
        prediction.predictions ||
        [];


    if (
        !Array.isArray(predictions) ||
        predictions.length === 0
    ) {

        container.innerHTML =
            '<div class="empty-tag">Top prediction details are not available.</div>';

        return;
    }


    predictions =
        predictions
            .filter(
                (item) => {

                    const name =
                        item &&
                        (
                            item.condition ||
                            item.label ||
                            ""
                        );

                    return (
                        name &&
                        !/^(min|mis|pe|eve|ge|me)\)?$/i.test(
                            String(name).trim()
                        )
                    );

                }
            )
            .slice(0, 5);


    const scores =
        predictions.map(
            (item) =>
                Number(
                    item.normalized_score ??
                    item.score ??
                    item.decision_score ??
                    0
                )
        );


    const total =
        scores.reduce(
            (sum, value) =>
                sum + (
                    Number.isFinite(value) &&
                    value > 0
                        ? value
                        : 0
                ),
            0
        );


    predictions.forEach(
        (item) => {

            const name =
                item.condition ||
                item.label ||
                "Unknown";


            const rawScore =
                Number(
                    item.normalized_score ??
                    item.score ??
                    item.decision_score ??
                    0
                );


            const percentage =
                total > 0
                    ? (
                        (
                            rawScore > 0
                                ? rawScore
                                : 0
                        ) /
                        total
                    ) * 100
                    : 0;


            const row =
                document.createElement(
                    "div"
                );


            row.className =
                "prediction-row";


            row.innerHTML = `
                <div class="prediction-name">
                    ${escapeHTML(
                        capitalizeWords(name)
                    )}
                </div>

                <div class="prediction-track">
                    <div
                        class="prediction-fill"
                        style="width: ${percentage}%"
                    ></div>
                </div>

                <div class="prediction-score">
                    ${percentage.toFixed(1)}%
                </div>
            `;


            container.appendChild(
                row
            );

        }
    );

}


